    private void btnaddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnaddActionPerformed
        // TODO add your handling code here:
     
try {

    // Check appointment selection
    if (cmbappointment.getSelectedItem() == null) {

        JOptionPane.showMessageDialog(
                this,
                "Please select an appointment.",
                "Validation Error",
                JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    // Get treatment data
    String diagnosis =
            txtdiagnosis.getText().trim();

    String description =
            txtdescription.getText().trim();

    String dateText =
            txtdate.getText().trim();

    String costText =
            txtcost.getText().trim();

    String medication =
            txtmedication.getText().trim();

    // Validate diagnosis
    ValidationUtil.validateRequired(
            diagnosis,
            "Diagnosis"
    );

    // Validate treatment description
    ValidationUtil.validateRequired(
            description,
            "Treatment description"
    );

    // Validate treatment date
    ValidationUtil.validateRequired(
            dateText,
            "Treatment date"
    );

    // Validate cost
    ValidationUtil.validateRequired(
            costText,
            "Cost"
    );

    // Convert date
    Date treatmentDate =
            Date.valueOf(dateText);

    // Convert cost
    double cost =
            Double.parseDouble(costText);

    // Get selected appointment ID
    int appointmentId =
            getSelectedAppointmentId();

    // Create Treatment object
    Treatment treatment =
            new Treatment(
                    appointmentId,
                    diagnosis,
                    description,
                    medication,
                    treatmentDate,
                    cost
            );

    // Add treatment
    boolean success =
            treatmentController.addTreatment(
                    treatment
            );

    if (success) {

        JOptionPane.showMessageDialog(
                this,
                "Treatment added successfully."
        );

        clearFields();
        loadTreatments();

    } else {

        JOptionPane.showMessageDialog(
                this,
                "Failed to add treatment.",
                "Database Error",
                JOptionPane.ERROR_MESSAGE
        );
    }

} catch (IllegalArgumentException e) {

    JOptionPane.showMessageDialog(
            this,
            "Invalid date or cost format.\n\n"
            + "Date: YYYY-MM-DD\n"
            + "Cost: Example 2500.00",
            "Validation Error",
            JOptionPane.WARNING_MESSAGE
    );

} catch (Exception e) {

    JOptionPane.showMessageDialog(
            this,
            "An unexpected error occurred.",
            "Error",
            JOptionPane.ERROR_MESSAGE
    );

    e.printStackTrace();
}
 
        
    }//GEN-LAST:event_btnaddActionPerformed

