    private void selectAppointment(String displayText) {

    for (int i = 0;
         i < cmbappointment.getItemCount();
         i++) {

        String item =
                cmbappointment.getItemAt(i);

        if (item.equals(displayText)) {

            cmbappointment.setSelectedIndex(i);

            return;
        }
    }
}
    private void clearFields() {

    txttreatmentid.setText("");

    if (cmbappointment.getItemCount() > 0) {
        cmbappointment.setSelectedIndex(0);
    }

    txtdiagnosis.setText("");
    txtdescription.setText("");
    txtmedication.setText("");
    txtdate.setText("");
    txtcost.setText("");
}
