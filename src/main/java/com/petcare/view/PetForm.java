    private void tblpetMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblpetMousePressed
        // TODO add your handling code here:
         int row = tblpet.getSelectedRow();

    if (row >= 0) {

        // Pet ID
        txtpetid.setText(
                tblpet.getValueAt(row, 0).toString()
        );

        // Customer ID from table
        int customerId = Integer.parseInt(
                tblpet.getValueAt(row, 1).toString()
        );

        // Find customer in ComboBox
        for (int i = 0; i < customers.size(); i++) {

            if (customers.get(i).getCustomerId() == customerId) {

                cmbcustomer.setSelectedIndex(i);
                break;
            }
        }

        // Pet Name
        txtpetname.setText(
                tblpet.getValueAt(row, 2).toString()
        );

        // Species
        txtspecies.setText(
                tblpet.getValueAt(row, 3).toString()
        );

        // Breed
        txtbreed.setText(
                tblpet.getValueAt(row, 4).toString()
        );

        // Gender
        String gender =
                tblpet.getValueAt(row, 5).toString();

        if (gender.equalsIgnoreCase("Male")) {

            rbmale.setSelected(true);

        } else if (gender.equalsIgnoreCase("Female")) {

            rbfemale.setSelected(true);
        }

        // DOB
        txtdob.setText(
                tblpet.getValueAt(row, 6).toString()
        );

        // Weight
        txtweight.setText(
                tblpet.getValueAt(row, 7).toString()
        );
    }

        
    }//GEN-LAST:event_tblpetMousePressed

