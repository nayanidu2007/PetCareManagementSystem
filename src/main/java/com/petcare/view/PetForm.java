    private void btndeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btndeleteActionPerformed
        // TODO add your handling code here:
     try {

    String petIdText = txtpetid.getText().trim();

    ValidationUtil.validateRequired(petIdText, "Pet ID");

    int petId;

    try {
        petId = Integer.parseInt(petIdText);
    } catch (NumberFormatException e) {
        throw new InvalidInputException("Pet ID must be a valid number.");
    }

    int confirm = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete this pet?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION
    );

    if (confirm == JOptionPane.YES_OPTION) {

        boolean success = petcontroller.deletePet(petId);

        if (success) {

            JOptionPane.showMessageDialog(
                    this,
                    "Pet deleted successfully!"
            );

            loadPets();
            clearFields();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Failed to delete pet.",
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }

} catch (InvalidInputException e) {

    JOptionPane.showMessageDialog(
            this,
            e.getMessage(),
            "Validation Error",
            JOptionPane.WARNING_MESSAGE
    );

} catch (Exception e) {

    JOptionPane.showMessageDialog(
            this,
            "Error: " + e.getMessage(),
            "Error",
            JOptionPane.ERROR_MESSAGE
    );
}
    }//GEN-LAST:event_btndeleteActionPerformed

