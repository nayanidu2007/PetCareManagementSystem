    private void btnaddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnaddActionPerformed
        // TODO add your handling code here:
        try {

    String petName = txtpetname.getText().trim();
    String species = txtspecies.getText().trim();
    String breed = txtbreed.getText().trim();
    String dob = txtdob.getText().trim();
    String weightText = txtweight.getText().trim();

    if (cmbcustomer.getSelectedItem() == null) {
        throw new InvalidInputException(
            "Please select a customer."
        );
    }

    ValidationUtil.validateRequired(
        petName, "Pet name"
    );

    ValidationUtil.validateRequired(
        species, "Species"
    );

    ValidationUtil.validateRequired(
        dob, "Date of birth"
    );

    ValidationUtil.validateRequired(
        weightText, "Weight"
    );

    if (!rbmale.isSelected() && !rbfemale.isSelected()) {
        throw new InvalidInputException(
            "Please select the pet's gender."
        );
    }

    double weight;

    try {
        weight = Double.parseDouble(weightText);
    } catch (NumberFormatException e) {
        throw new InvalidInputException(
            "Weight must be a valid number."
        );
    }

    ValidationUtil.validatePositiveNumber(
        weight, "Weight"
    );

    java.sql.Date dateOfBirth;

    try {
        dateOfBirth = java.sql.Date.valueOf(dob);
    } catch (IllegalArgumentException e) {
        throw new InvalidInputException(
            "Date must use YYYY-MM-DD format."
        );
    }

    int customerId = Integer.parseInt(
        cmbcustomer.getSelectedItem()
            .toString()
            .split(" - ")[0]
    );

    String gender =
        rbmale.isSelected() ? "Male" : "Female";

    pet newPet = new pet(
        0,
        customerId,
        petName,
        species,
        breed,
        gender,
        dateOfBirth,
        weight
    );

    if (petcontroller.addPet(newPet)) {

        JOptionPane.showMessageDialog(
            this,
            "Pet added successfully!"
        );

        loadPets();
        clearFields();

    } else {

        JOptionPane.showMessageDialog(
            this,
            "Failed to add pet!"
        );
    }

} catch (InvalidInputException e) {

    JOptionPane.showMessageDialog(
        this,
        e.getMessage(),
        "Validation Error",
        JOptionPane.WARNING_MESSAGE
    );

} catch (Exception e) {

    JOptionPane.showMessageDialog(
        this,
        "An unexpected error occurred.",
        "Error",
        JOptionPane.ERROR_MESSAGE
    );

    e.printStackTrace();
}
        
    }//GEN-LAST:event_btnaddActionPerformed
