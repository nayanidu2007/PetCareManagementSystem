   private void selectComboItem(
        javax.swing.JComboBox<String> comboBox,
        String displayText) {

    for (int i = 0; i < comboBox.getItemCount(); i++) {

        String item = comboBox.getItemAt(i);

        if (item.equals(displayText)) {

            comboBox.setSelectedIndex(i);
            return;
        }
    }
}
