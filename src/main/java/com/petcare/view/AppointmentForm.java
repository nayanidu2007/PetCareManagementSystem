    private void btnaddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnaddActionPerformed
        // TODO add your handling code here:
        
          try {

        // CHECK PET
        if (cmbpet.getSelectedItem() == null) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please select a pet."
            );

            return;
        }


        // CHECK VETERINARIAN
        if (cmbveterinarian.getSelectedItem() == null) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please select a veterinarian."
            );

            return;
        }


        // GET PET ID
       int petId = Integer.parseInt(
        cmbpet.getSelectedItem().toString().split(" - ")[0]
            );


        // GET VETERINARIAN ID
        int veterinarianId = Integer.parseInt(
        cmbveterinarian.getSelectedItem().toString().split(" - ")[0]
            );


        // DATE
        String dateText =
                txtdate.getText().trim();

        if (dateText.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please enter appointment date."
            );

            return;
        }

        Date appointmentDate =
                Date.valueOf(dateText);


        // TIME
        String timeText =
                txttime.getText().trim();

        if (timeText.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please enter appointment time."
            );

            return;
        }

        Time appointmentTime =
                Time.valueOf(timeText);


        // REASON
        String reason =
                txtreson.getText().trim();

        if (reason.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please enter appointment reason."
            );

            return;
        }


        // STATUS
        String status =
                cmbstatus.getSelectedItem().toString();


        // NOTES
        String notes =
                txtnotes.getText().trim();


        // CREATE APPOINTMENT OBJECT
        Apointment appointment =
                new Apointment(
                        petId,
                        veterinarianId,
                        appointmentDate,
                        appointmentTime,
                        reason,
                        status,
                        notes
                );


        // SAVE TO DATABASE
        boolean success =
                appointmentController
                        .addAppointment(appointment);


        if (success) {

            JOptionPane.showMessageDialog(
                    this,
                    "Appointment added successfully."
            );

            clearFields();

            loadAppointments();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Failed to add appointment."
            );
        }


    } catch (IllegalArgumentException e) {

        JOptionPane.showMessageDialog(
                this,
                "Invalid date or time format.\n\n"
                + "Date: YYYY-MM-DD\n"
                + "Time: HH:MM:SS"
        );

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                "Error: " + e.getMessage()
        );

        e.printStackTrace();
    }
    }//GEN-LAST:event_btnaddActionPerformed

