    private void btndeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btndeleteActionPerformed
      try {

    String appointmentIdText =
            txtappointmentid.getText().trim();

    ValidationUtil.validateRequired(
            appointmentIdText,
            "Appointment ID"
    );

    int appointmentId;

    try {

        appointmentId =
                Integer.parseInt(appointmentIdText);

    } catch (NumberFormatException e) {

        throw new InvalidInputException(
                "Appointment ID must be a valid number."
        );
    }

    int confirm =
            JOptionPane.showConfirmDialog(
                    this,
                    "Are you sure you want to delete this appointment?",
                    "Confirm Delete",
                    JOptionPane.YES_NO_OPTION
            );

    if (confirm == JOptionPane.YES_OPTION) {

        boolean success =
                appointmentController
                        .deleteAppointment(appointmentId);

        if (success) {

            JOptionPane.showMessageDialog(
                    this,
                    "Appointment deleted successfully!"
            );

            loadAppointments();
            clearFields();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Failed to delete appointment.",
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }

} catch (InvalidInputException e) {

    JOptionPane.showMessageDialog(
            this,
            e.getMessage(),
            "Validation Error",
            JOptionPane.WARNING_MESSAGE
    );

} catch (Exception e) {

    JOptionPane.showMessageDialog(
            this,
            "An unexpected error occurred.",
            "Error",
            JOptionPane.ERROR_MESSAGE
    );

    e.printStackTrace();
}
    }//GEN-LAST:event_btndeleteActionPerformed

    
    private void clearFields() {

    txtappointmentid.setText("");

    if (cmbpet.getItemCount() > 0) {
        cmbpet.setSelectedIndex(0);
    }

    if (cmbveterinarian.getItemCount() > 0) {
        cmbveterinarian.setSelectedIndex(0);
    }

    txtdate.setText("");
    txttime.setText("");
    txtreson.setText("");

    if (cmbstatus.getItemCount() > 0) {
        cmbstatus.setSelectedIndex(0);
    }

    txtnotes.setText("");
}
