     private void loadPets() {

    

    pets = petDAO.getAllPets();

    cmbpet.removeAllItems();

    for (pet pet : pets) {
        cmbpet.addItem(
            pet.getpetId() + " - " + pet.getpetName()
        );
    }
}
     
      private void loadVeterinarians() {

    

    veterinarians = veterinarianDAO.getAllVeterinarian();

    cmbveterinarian.removeAllItems();

    for (Veterinarian Veterinarian : veterinarians) {
        cmbveterinarian.addItem(
            Veterinarian.getveterinaryId() + " - " + Veterinarian.getfullName()
        );
    }
}
      
      private void loadAppointments() {

    DefaultTableModel model =
            (DefaultTableModel) tblappointment.getModel();

    model.setRowCount(0);

    List<Apointment> appointments =
            appointmentController.getAllAppointments();

    for (Apointment appointment : appointments) {

        model.addRow(new Object[]{

            appointment.getAppointmentId(),

            getPetDisplayName(
                    appointment.getPetId()
            ),

            getVeterinarianDisplayName(
                    appointment.getVeterinarianId()
            ),

            appointment.getAppointmentDate(),

            appointment.getAppointmentTime(),

            appointment.getReason(),

            appointment.getStatus(),

            appointment.getNotes()
        });
    }
}
      private String getPetDisplayName(int petId) {

    for (pet p : pets) {

        if (p.getpetId() == petId) {
            return p.getpetName();
        }
    }

    return String.valueOf(petId);
}

private String getVeterinarianDisplayName(int veterinarianId) {

    for (Veterinarian veterinarian : veterinarians) {

        if (veterinarian.getveterinaryId() == veterinarianId) {
            return veterinarian.getfullName();
        }
    }

    return String.valueOf(veterinarianId);
}

