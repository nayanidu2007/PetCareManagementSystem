    private void btnaddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnaddActionPerformed
    // TODO add your handling code here:

try {

    String name = full_nametxt.getText().trim();
    String phone = phonetxt.getText().trim();
    String email = emailtxt.getText().trim();
    String address = addresstxt.getText().trim();

    // Validate customer name
    ValidationUtil.validateRequired(
        name,
        "Customer name"
    );

    // Validate phone number
    ValidationUtil.validatePhone(phone);

    // Validate email
    ValidationUtil.validateEmail(email);

    // Validate address
    ValidationUtil.validateRequired(
        address,
        "Address"
    );

    // Create Customer object
    Customer c = new Customer();

    c.setFullName(name);
    c.setPhone(phone);
    c.setEmail(email);
    c.setAddress(address);

    // Add customer to database
    if (customerDAO.addCustomer(c)) {

        JOptionPane.showMessageDialog(
            this,
            "Customer added successfully!"
        );

        loadCustomers();
        clearFields();

    } else {

        JOptionPane.showMessageDialog(
            this,
            "Failed to add customer!",
            "Database Error",
            JOptionPane.ERROR_MESSAGE
        );
    }

} catch (InvalidInputException e) {

    JOptionPane.showMessageDialog(
        this,
        e.getMessage(),
        "Validation Error",
        JOptionPane.WARNING_MESSAGE
    );

} catch (Exception e) {

    JOptionPane.showMessageDialog(
        this,
        "An unexpected error occurred.",
        "Error",
        JOptionPane.ERROR_MESSAGE
    );

    e.printStackTrace();
}
    }//GEN-LAST:event_btnaddActionPerformed

    private void btnupdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnupdateActionPerformed
         try {

        String idText =
                customer_idtxt.getText().trim();

        ValidationUtil.validateRequired(
                idText,
                "Customer ID"
        );

        int customerId;

        try {

            customerId =
                    Integer.parseInt(idText);

        } catch (NumberFormatException e) {

            throw new InvalidInputException(
                    "Customer ID must be a valid number."
            );
        }


        String name =
                full_nametxt.getText().trim();

        String phone =
                phonetxt.getText().trim();

        String email =
                emailtxt.getText().trim();

        String address =
                addresstxt.getText().trim();


        // Validate name
        ValidationUtil.validateRequired(
                name,
                "Customer name"
        );


        // Validate phone
        ValidationUtil.validatePhone(phone);


        // Validate email
        ValidationUtil.validateEmail(email);


        // Validate address
        ValidationUtil.validateRequired(
                address,
                "Address"
        );


        Customer c = new Customer();

        c.setCustomerId(customerId);
        c.setFullName(name);
        c.setPhone(phone);
        c.setEmail(email);
        c.setAddress(address);


        boolean success =
                customerDAO.updateCustomer(c);


        if (success) {

            JOptionPane.showMessageDialog(
                    this,
                    "Customer updated successfully!"
            );

            loadCustomers();
            clearFields();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Failed to update customer!",
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }


    } catch (InvalidInputException e) {

        JOptionPane.showMessageDialog(
                this,
                e.getMessage(),
                "Validation Error",
                JOptionPane.WARNING_MESSAGE
        );

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                "An unexpected error occurred.",
                "Error",
                JOptionPane.ERROR_MESSAGE
        );

        e.printStackTrace();
    }
    }//GEN-LAST:event_btnupdateActionPerformed

    private void tblCustomersMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblCustomersMousePressed
        // TODO add your handling code here:
         int row = tblCustomers.getSelectedRow();
        if (row >= 0) {
            selectedId = Integer.parseInt(tblCustomers.getValueAt(row, 0).toString());
            customer_idtxt.setText(String.valueOf(selectedId));
            full_nametxt.setText(tblCustomers.getValueAt(row, 1).toString());
            phonetxt.setText(tblCustomers.getValueAt(row, 2).toString());
            emailtxt.setText(tblCustomers.getValueAt(row, 3).toString());
            addresstxt.setText(tblCustomers.getValueAt(row, 4).toString());
        }
    }//GEN-LAST:event_tblCustomersMousePressed

    private void btndeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btndeleteActionPerformed
         try {

        String idText =
                customer_idtxt.getText().trim();

        ValidationUtil.validateRequired(
                idText,
                "Customer ID"
        );

        int customerId;

        try {

            customerId =
                    Integer.parseInt(idText);

        } catch (NumberFormatException e) {

            throw new InvalidInputException(
                    "Customer ID must be a valid number."
            );
        }


        int confirm =
                JOptionPane.showConfirmDialog(
                        this,
                        "Are you sure you want to delete this customer?",
                        "Confirm Delete",
                        JOptionPane.YES_NO_OPTION
                );


        if (confirm == JOptionPane.YES_OPTION) {

            boolean success =
                    customerDAO.deleteCustomer(customerId);


            if (success) {

                JOptionPane.showMessageDialog(
                        this,
                        "Customer deleted successfully!"
                );

                loadCustomers();
                clearFields();

            } else {

                JOptionPane.showMessageDialog(
                        this,
                        "Failed to delete customer!",
                        "Database Error",
                        JOptionPane.ERROR_MESSAGE
                );
            }
        }


    } catch (InvalidInputException e) {

        JOptionPane.showMessageDialog(
                this,
                e.getMessage(),
                "Validation Error",
                JOptionPane.WARNING_MESSAGE
        );

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                "An unexpected error occurred.",
                "Error",
                JOptionPane.ERROR_MESSAGE
        );

        e.printStackTrace();
    }
    }//GEN-LAST:event_btndeleteActionPerformed

