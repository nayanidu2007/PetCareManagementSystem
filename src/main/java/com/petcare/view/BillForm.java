    private void loadAppointments() {

    cmbappointment.removeAllItems();

    appointments = appointmentDAO.getAllAppointments();

    for (Apointment appointment : appointments) {

        cmbappointment.addItem(
            appointment.getAppointmentId()
            + " - "
            + appointment.getReason()
        );
    }
}
    private String getAppointmentDisplayName(int appointmentId) {

    for (Apointment appointment : appointments) {

        if (appointment.getAppointmentId() == appointmentId) {

            return appointment.getAppointmentId()
                    + " - "
                    + appointment.getReason();
        }
    }

    return "";
}
    private int getSelectedAppointmentId() {

    if (cmbappointment.getSelectedItem() == null) {
        return -1;
    }

    String selected =
            cmbappointment.getSelectedItem().toString();

    return Integer.parseInt(
            selected.split(" - ")[0]
    );
}
    private void selectAppointment(int appointmentId) {

    for (int i = 0; i < cmbappointment.getItemCount(); i++) {

        String item = cmbappointment.getItemAt(i);

        if (item.startsWith(appointmentId + " - ")) {

            cmbappointment.setSelectedIndex(i);
            return;
        }
    }
}
    private void loadBills() {

    tableModel.setRowCount(0);

    List<Bill> bills = billController.getAllBills();

    for (Bill bill : bills) {

        tableModel.addRow(new Object[]{
            bill.getBillId(),
            getAppointmentDisplayName(
                bill.getAppointmentId()
            ),
            bill.getBillDate(),
            bill.getTotalAmount(),
            bill.getPaymentMethod(),
            bill.getPaymentStatus()
        });
    }
}

