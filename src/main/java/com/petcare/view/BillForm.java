    private void btnaddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnaddActionPerformed
        // TODO add your handling code here:
         
try {

    // Check appointment selection
    if (cmbappointment.getSelectedItem() == null) {

        JOptionPane.showMessageDialog(
                this,
                "Please select an appointment.",
                "Validation Error",
                JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    // Get appointment ID
    int appointmentId =
            getSelectedAppointmentId();

    // Get bill date
    String dateText =
            txtdate.getText().trim();

    // Validate bill date
    ValidationUtil.validateRequired(
            dateText,
            "Bill date"
    );

    // Convert date
    Date billDate =
            Date.valueOf(dateText);

    // Get amount
    String amountText =
            txtamount.getText().trim();

    // Validate amount
    ValidationUtil.validateRequired(
            amountText,
            "Total amount"
    );

    // Convert amount
    double totalAmount =
            Double.parseDouble(amountText);

    // Validate amount
    if (totalAmount < 0) {

        JOptionPane.showMessageDialog(
                this,
                "Amount cannot be negative.",
                "Validation Error",
                JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    // Check payment method
    if (cmbpaymentmethord.getSelectedItem() == null) {

        JOptionPane.showMessageDialog(
                this,
                "Please select payment method.",
                "Validation Error",
                JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    String paymentMethod =
            cmbpaymentmethord
            .getSelectedItem()
            .toString();

    // Check payment status
    if (cmbpaymentstatus.getSelectedItem() == null) {

        JOptionPane.showMessageDialog(
                this,
                "Please select payment status.",
                "Validation Error",
                JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    String paymentStatus =
            cmbpaymentstatus
            .getSelectedItem()
            .toString();

    // Create Bill object
    Bill bill =
            new Bill(
                    appointmentId,
                    billDate,
                    totalAmount,
                    paymentMethod,
                    paymentStatus
            );

    // Add bill
    boolean success =
            billController.addBill(bill);

    if (success) {

        JOptionPane.showMessageDialog(
                this,
                "Bill added successfully."
        );

        loadBills();
        clearFields();

    } else {

        JOptionPane.showMessageDialog(
                this,
                "Failed to add bill.",
                "Database Error",
                JOptionPane.ERROR_MESSAGE
        );
    }

} catch (IllegalArgumentException e) {

    JOptionPane.showMessageDialog(
            this,
            "Invalid date or amount.\n\n"
            + "Date format: YYYY-MM-DD\n"
            + "Example: 2026-10-04\n"
            + "Amount: Example 2500.00",
            "Validation Error",
            JOptionPane.WARNING_MESSAGE
    );

} catch (Exception e) {

    JOptionPane.showMessageDialog(
            this,
            "An unexpected error occurred.",
            "Error",
            JOptionPane.ERROR_MESSAGE
    );

    e.printStackTrace();
}


    }//GEN-LAST:event_btnaddActionPerformed

