    private void loadVeterinarians()
    {
        DefaultTableModel model = (DefaultTableModel)tblveterinarian.getModel();
        model.setRowCount(0);
        
        List<Veterinarian>veterinarians = veterinarianController.getAllVeterinarian();
        
        for (Veterinarian veterinarian : veterinarians )
        {
            model.addRow(new Object[]{
            
                veterinarian.getveterinaryId(),
                veterinarian.getfullName(),
                veterinarian.getPhone(),
                veterinarian.getemail(),
                veterinarian.getSpecialization()
            });
        }
    }

