    private void btnaddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnaddActionPerformed
     try {

    String fullName = txtfullname.getText().trim();
    String phone = txtphone.getText().trim();
    String email = txtemail.getText().trim();
    String specialization =
            txtspecialization.getText().trim();

    // Validate veterinarian name
    ValidationUtil.validateRequired(
            fullName,
            "Veterinarian name"
    );

    // Validate phone number
    ValidationUtil.validatePhone(phone);

    // Validate email
    ValidationUtil.validateEmail(email);

    // Validate specialization
    ValidationUtil.validateRequired(
            specialization,
            "Specialization"
    );

    // Create Veterinarian object
    Veterinarian veterinarian =
            new Veterinarian(
                    fullName,
                    phone,
                    email,
                    specialization
            );

    // Add veterinarian
    boolean success =
            veterinarianController.addVeterinarian(
                    veterinarian
            );

    if (success) {

        JOptionPane.showMessageDialog(
                this,
                "Veterinarian added successfully."
        );

        clearFields();
        loadVeterinarians();

    } else {

        JOptionPane.showMessageDialog(
                this,
                "Failed to add veterinarian.",
                "Database Error",
                JOptionPane.ERROR_MESSAGE
        );
    }

} catch (InvalidInputException e) {

    JOptionPane.showMessageDialog(
            this,
            e.getMessage(),
            "Validation Error",
            JOptionPane.WARNING_MESSAGE
    );

} catch (Exception e) {

    JOptionPane.showMessageDialog(
            this,
            "An unexpected error occurred.",
            "Error",
            JOptionPane.ERROR_MESSAGE
    );

    e.printStackTrace();

    }
         
        
        
    }//GEN-LAST:event_btnaddActionPerformed

    private void btnupdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnupdateActionPerformed
      try {

    // Check whether a veterinarian is selected
    String idText =
            txtveterinarianid.getText().trim();

    if (idText.isEmpty()) {

        throw new InvalidInputException(
                "Please select a veterinarian from the table."
        );
    }

    int veterinarianId;

    // Validate ID
    try {

        veterinarianId =
                Integer.parseInt(idText);

    } catch (NumberFormatException e) {

        throw new InvalidInputException(
                "Invalid veterinarian ID."
        );
    }

    String fullName =
            txtfullname.getText().trim();

    String phone =
            txtphone.getText().trim();

    String email =
            txtemail.getText().trim();

    String specialization =
            txtspecialization.getText().trim();

    // Validate veterinarian name
    ValidationUtil.validateRequired(
            fullName,
            "Veterinarian name"
    );

    // Validate phone
    ValidationUtil.validatePhone(phone);

    // Validate email
    ValidationUtil.validateEmail(email);

    // Validate specialization
    ValidationUtil.validateRequired(
            specialization,
            "Specialization"
    );

    // Create Veterinarian object
    Veterinarian veterinarian =
            new Veterinarian(
                    veterinarianId,
                    fullName,
                    phone,
                    email,
                    specialization
            );

    // Update veterinarian
    boolean success =
            veterinarianController.updateVeterinarian(
                    veterinarian
            );

    if (success) {

        JOptionPane.showMessageDialog(
                this,
                "Veterinarian updated successfully."
        );

        clearFields();
        loadVeterinarians();

    } else {

        JOptionPane.showMessageDialog(
                this,
                "Failed to update veterinarian.",
                "Database Error",
                JOptionPane.ERROR_MESSAGE
        );
    }

} catch (InvalidInputException e) {

    JOptionPane.showMessageDialog(
            this,
            e.getMessage(),
            "Validation Error",
            JOptionPane.WARNING_MESSAGE
    );

} catch (Exception e) {

    JOptionPane.showMessageDialog(
            this,
            "An unexpected error occurred.",
            "Error",
            JOptionPane.ERROR_MESSAGE
    );

    e.printStackTrace();
}
    }//GEN-LAST:event_btnupdateActionPerformed

    private void btndeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btndeleteActionPerformed
        // TODO add your handling code here:
         if (txtveterinarianid.getText().trim().isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Please select a veterinarian first."
        );

        return;
    }


    int veterinarianId =
            Integer.parseInt(
                    txtveterinarianid.getText()
            );


    int confirm = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete this veterinarian?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION
    );


    if (confirm != JOptionPane.YES_OPTION) {
        return;
    }


    boolean success =
            veterinarianController.deleteVeterinarian(
                    veterinarianId
            );


    if (success) {

        JOptionPane.showMessageDialog(
                this,
                "Veterinarian deleted successfully."
        );

        clearFields();
        loadVeterinarians();

    } else {

        JOptionPane.showMessageDialog(
                this,
                "Unable to delete veterinarian."
                + "\nThey may already be linked to an appointment."
        );
    }
    }//GEN-LAST:event_btndeleteActionPerformed

